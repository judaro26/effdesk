// scripts/test-fields.js: CUSTOM TICKET FIELDS ON A REAL POSTGRES.
import crypto from 'crypto';
import { check, done } from './lib/check.js';
import { freshDb } from './lib/pg-temp.js';
import { migrate } from './migrate.js';
import { makePool } from '../src/db.js';
import { makeAuth } from '../src/auth.js';
import { makeMailer } from '../src/email.js';
import { tickets, inboundEmail } from '../src/handlers.js';
import { grantLicense } from '../src/license.js';
import { ticketToken } from '../src/ticket-mail.js';
import { roundRobin, runTriggers } from '../src/triggers.js';
import { withOrg } from '../src/db.js';

const SECRET = crypto.randomBytes(32).toString('base64'), PW = 'correct horse battery', WH = 'whsec_' + crypto.randomBytes(24).toString('base64');
const ENV = { INBOUND_DOMAIN: 'in.effdesk.test', BETTER_AUTH_SECRET: SECRET, RESEND_WEBHOOK_SECRET: WH, RESEND_API_KEY: 're_test' };
const { url } = await freshDb('fields'); await migrate(url);
const pool = makePool(url), outbox = [];
const mailer = makeMailer({ transport: async m => { outbox.push(m); } });
const auth = makeAuth({ pool, mailer, secret: SECRET, baseURL: 'http://localhost:8888', requireVerified: false });
const signUp = async (email, name) => { await auth.api.signUpEmail({ body: { email, password: PW, name } }); const r = await auth.api.signInEmail({ body: { email, password: PW }, returnHeaders: true }); const cookie = r.headers.get('set-cookie').split(/,(?=[^;]+=)/).map(c => c.split(';')[0]).join('; '); return { cookie, headers: new Headers({ cookie }), user: r.response.user }; };
const olivia = await signUp('olivia@acme.test', 'Olivia'), ann = await signUp('ann@acme.test', 'Ann'), otto = await signUp('otto@beta.test', 'Otto');
const acme = await auth.api.createOrganization({ body: { name: 'Acme', slug: 'acme' }, headers: olivia.headers });
const beta = await auth.api.createOrganization({ body: { name: 'Beta', slug: 'beta' }, headers: otto.headers });
await auth.api.addMember({ body: { userId: ann.user.id, role: 'member', organizationId: acme.id } });
await grantLicense(pool, { orgId: acme.id, actorEmail: 'owner@effdesk.test', note: 'test' });
const call = async (who, body) => { const r = await tickets(new Request('http://x/api/tickets', { method: 'POST', headers: { 'content-type': 'application/json', cookie: who.cookie }, body: JSON.stringify(body) }), { pool, auth, mailer, env: ENV }); return { status: r.status, body: await r.json() }; };
const A = (who, action, extra = {}) => call(who, { orgId: acme.id, action, ...extra }), B = (who, action, extra = {}) => call(who, { orgId: beta.id, action, ...extra });
const mkf = (o) => A(olivia, 'field-save', o);
const f1 = await mkf({ label: 'Order number', type: 'text' });
check('a field is created with a key made from its name', f1.status === 200 && f1.body.key === 'order_number');
const f2 = await mkf({ label: 'Product', type: 'dropdown', options: 'Basic\nPro' });
const f3 = await mkf({ label: 'Urgent call', type: 'checkbox' });
const f4 = await mkf({ label: 'Units', type: 'number' });
check('fields list in order with types', (await A(olivia, 'fields-list')).body.fields.length === 4);
check('a dropdown needs choices and a bad type is refused', (await mkf({ label: 'Empty', type: 'dropdown', options: '' })).status === 400 && (await mkf({ label: 'Weird', type: 'zzz' })).status === 400);
check('init carries the fields', (await A(olivia, 'init')).body.fields.length === 4);
const c = await A(olivia, 'create', { subject: 'Cf', body: 'x', requesterEmail: 'c@x.co', custom: { order_number: 'A-1', product: 'Pro', urgent_call: true, units: '3' } });
check('a ticket can be created with custom values', c.status === 200 && c.body.ticket.custom.order_number === 'A-1' && c.body.ticket.custom.units === 3 && c.body.ticket.custom.urgent_call === true);
check('a bad dropdown value is refused', (await A(olivia, 'create', { subject: 'Bad', body: 'x', requesterEmail: 'c@x.co', custom: { product: 'Nope' } })).status === 400);
const n = c.body.ticket.number;
const u = await A(olivia, 'update', { number: n, patch: { custom: { order_number: 'B-2' } } });
const g = (await A(olivia, 'get', { number: n })).body;
check('an update merges and logs the change', u.status === 200 && g.ticket.custom.order_number === 'B-2' && g.ticket.custom.product === 'Pro');
await A(olivia, 'update', { number: n, patch: { custom: { product: '' } } });
check('an empty value clears a field', !('product' in (await A(olivia, 'get', { number: n })).body.ticket.custom));
const fd = await A(olivia, 'field-delete', { id: f4.body.id });
check('a field can be deleted', fd.status === 200 && (await A(olivia, 'fields-list')).body.fields.length === 3);
check('members cannot manage fields', (await A(ann, 'field-save', { label: 'X', type: 'text' })).status === 403);
check('another organization is not on a plan with fields', (await B(otto, 'field-save', { label: 'X', type: 'text' })).status === 402 && (await B(otto, 'fields-list')).body.fields.length === 0);
await pool.end(); done();
