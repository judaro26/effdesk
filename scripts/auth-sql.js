// scripts/auth-sql.js: writes migrations/001_auth.sql from the Better Auth configuration (run it after changing src/auth.js plugins; a test fails when the file is out of date).
// Usage: npm run auth:sql   (uses a throwaway local Postgres, or the EMPTY database in DATABASE_URL)
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
import { getMigrations } from 'better-auth/db/migration';
import pg from 'pg';
import { authOptions } from '../src/auth.js';
import { freshDb } from './lib/pg-temp.js';
export async function compile(url) {
  const pool = new pg.Pool({ connectionString: url });
  try { const { compileMigrations } = await getMigrations(authOptions({ pool, mailer: {}, secret: 'x'.repeat(32) })); return await compileMigrations(); } finally { await pool.end(); }
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'migrations', '001_auth.sql');
  (process.env.DATABASE_URL ? Promise.resolve(process.env.DATABASE_URL) : freshDb('authsql').then(d => d.url)).then(compile).then(sql => { fs.writeFileSync(out, '-- 001_auth.sql: GENERATED by scripts/auth-sql.js from the Better Auth configuration. Do not edit by hand; change src/auth.js and regenerate.\n' + sql + '\n'); console.log('wrote', out); }, e => { console.error(e); process.exit(1); });
}
